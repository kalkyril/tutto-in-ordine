'use strict'
// Prove del blocco con password (impronta, tentativi, rallentamento, file, stato).
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const blocco = require('../electron/blocco')
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mngmnt-blocco-'))
let n = 0; const ok = (t) => console.log(`ok ${++n} - ${t}`)

blocco.init(dir)
assert.deepEqual(blocco.stato(), { attivo: false, bloccato: false, minuti: 0 }); assert.equal(blocco.blocca().bloccato, false); assert.equal(blocco.èBloccato(), false)
ok('senza password il blocco non si attiva mai')
assert.throws(() => blocco.imposta('abc', 5), /almeno 6/)
blocco.imposta('Segreta!2026', 10)
const raw = fs.readFileSync(path.join(dir, 'blocco.json'), 'utf8')
assert.ok(!raw.includes('Segreta') && /"hash":"[0-9a-f]{64}"/.test(raw) && /"sale":"[0-9a-f]{32}"/.test(raw)); if (process.platform !== 'win32') assert.equal(fs.statSync(path.join(dir, 'blocco.json')).mode & 0o077, 0)
ok('password mai salvata in chiaro: impronta scrypt con sale casuale, file leggibile solo dal proprietario')
blocco.init(dir); assert.equal(blocco.stato().bloccato, true); assert.equal(blocco.èBloccato(), true); assert.equal(blocco.stato().minuti, 10)
ok("all'avvio con password attiva l'app parte bloccata")
const t0 = 1_000_000
assert.equal(blocco.sblocca.length, 1)
assert.equal(blocco.verifica('sbagliata', t0), false)
assert.throws(() => blocco.verifica('Segreta!2026', t0 + 500), /riprova tra 1 secondi/)
assert.equal(blocco.verifica('altra', t0 + 1000), false); assert.throws(() => blocco.verifica('Segreta!2026', t0 + 2500), /riprova tra 1 secondi/)
assert.equal(blocco.verifica('Segreta!2026', t0 + 3100), true)
for (let i = 0, t = t0 + 10000; i < 8; i++, t += 40000) assert.equal(blocco.verifica('x', t), false)
assert.throws(() => blocco.verifica('Segreta!2026', t0 + 10000 + 8 * 40000 - 40000 + 1000), /riprova tra/)
ok('tentativi sbagliati: attesa crescente (1, 2, 4… fino a 30 secondi) anche con la password giusta; dopo l\'attesa e il tentativo giusto si azzera')
blocco.init(dir) // azzera il rallentamento (riavvio)
assert.equal(blocco.sblocca('no'), false); assert.equal(blocco.èBloccato(), true)
const fra = Date.now(); while (Date.now() - fra < 1100); // attende il rallentamento reale
assert.equal(blocco.sblocca('Segreta!2026'), true); assert.equal(blocco.èBloccato(), false); assert.equal(blocco.blocca().bloccato, true)
ok('sblocca solo con la password giusta; blocca di nuovo a richiesta')
assert.throws(() => blocco.imposta('Nuova-pw-99', 5, 'sbagliata'), /attuale errata|Troppi/)
blocco.init(dir); const f2 = Date.now(); while (Date.now() - f2 < 100); blocco.imposta('Nuova-pw-99', 20, 'Segreta!2026')
assert.equal(blocco.stato().minuti, 20); blocco.init(dir); assert.equal(blocco.sblocca('Segreta!2026'), false)
const f3 = Date.now(); while (Date.now() - f3 < 1100); assert.equal(blocco.sblocca('Nuova-pw-99'), true)
ok('cambio password: richiede quella attuale; la vecchia non vale più')
blocco.cambiaMinuti(999, 'Nuova-pw-99'); assert.equal(blocco.stato().minuti, 480); blocco.cambiaMinuti(-4, 'Nuova-pw-99'); assert.equal(blocco.stato().minuti, 0)
ok('minuti di inattività limitati tra 0 e 480')
assert.throws(() => blocco.rimuovi('no'), /errata|Troppi/); blocco.init(dir); blocco.blocca(); const f4 = Date.now(); while (Date.now() - f4 < 100);
blocco.rimuovi('Nuova-pw-99'); assert.equal(blocco.attivo(), false); assert.ok(!fs.existsSync(path.join(dir, 'blocco.json'))); assert.equal(blocco.èBloccato(), false)
ok('rimozione del blocco: serve la password; il file sparisce')
fs.writeFileSync(path.join(dir, 'blocco.json'), '{non json'); blocco.init(dir); assert.equal(blocco.attivo(), true); assert.equal(blocco.èBloccato(), true); assert.throws(() => blocco.sblocca('qualunque'), /danneggiata/)
ok('file del blocco illeggibile: accesso negato con errore esplicito')
fs.rmSync(dir, { recursive: true, force: true })
console.log(`\n${n} prove superate`)
