'use strict'
const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const db = require('../electron/db'), backup = require('../electron/backup'), importer = require('../electron/proforma-import')
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mngmnt-proforma-review-'))
let n = 0; const ok = s => console.log(`ok ${++n} - ${s}`)
try {
  db.open(path.join(root, 'data'))
  const imported = importer.interpreta('Onorari € 100,00\nAcconto € 20,00\nNetto a pagare € 80,00')
  assert.ok(imported.avvisi.some(s => s.includes('acconti')))
  let p = db.saveParcella({ data: '2026-10-14', tipo: 'proforma', stato: 'bozza', netto: 100, totale: 100, voci: imported.voci, importazione: { version: 1, nettoOriginale: imported.nettoOriginale } })
  const meta = () => JSON.parse(db.getParcella(p.id).importazione)
  assert.equal(meta().verificato, false); assert.equal(meta().nettoOriginale, 80)
  ok('acconti segnalati; originale e revisione pendente conservati nella bozza')
  assert.throws(() => db.saveParcella({ ...p, stato: 'emessa' }), /Verifica/)
  assert.equal(db.getParcella(p.id).stato, 'bozza'); ok('emissione senza verifica rifiutata senza modificare la bozza')
  p = db.saveParcella({ ...p, verificaImportazione: true })
  assert.equal(meta().verificato, true); assert.ok(meta().verificatoIl)
  p = db.saveParcella({ ...p, note: 'Nota facoltativa' }); assert.equal(meta().verificato, true)
  ok('verifica esplicita persistente; modifica di una nota non invalida i dati contabili')
  p = db.saveParcella({ ...p, voci: [{ ...p.voci[0], importo: 90 }], netto: 90, totale: 90 })
  assert.equal(meta().verificato, false); assert.equal(meta().nettoOriginale, 80)
  ok('modifica di importi o voci richiede nuova verifica e conserva il totale originale')
  p = db.saveParcella({ ...p, verificaImportazione: true }); const cli = db.save('anagrafica', { denominazione: 'Altro destinatario' })
  p = db.saveParcella({ ...p, cliente_id: cli.id, importazione: null })
  assert.equal(meta().verificato, false); assert.equal(meta().nettoOriginale, 80)
  ok('cambio destinatario invalida la verifica; omettere i metadati non li cancella')
  const handlers = new Map(); require('../electron/ipc/dati')({ handle: (k,f) => handlers.set(k,f), changed: () => {}, onSettings: () => {} })
  assert.throws(() => handlers.get('db:save')('parcelle', { id: p.id, importazione: null }), /editor/)
  ok('canale generico non rimuove la revisione persistente')
  const b = backup.run(path.join(root, 'backups')); db.close(); db.open(path.join(root, 'data')); assert.equal(meta().verificato, false)
  backup.restore(b); assert.equal(meta().nettoOriginale, 80); assert.equal(meta().verificato, false)
  ok('revisione e differenza conservate dopo riavvio e backup/ripristino')
  for (const text of ['Onorari € 100,00\nBollo € -2,00', 'Onorari € 100,00\nNetto a pagare € -1,00']) assert.throws(() => importer.interpreta(text), /Importo non valido/)
  ok('bollo e netto negativi rifiutati durante l’importazione')
} finally { db.close(); fs.rmSync(root, { recursive: true, force: true }) }
console.log(`${n} prove revisione pro forma superate`)
