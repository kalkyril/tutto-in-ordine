'use strict'
const assert = require('node:assert/strict'), fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { scan, ignored } = require('./check-publication')
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mngmnt-publication-'))
let n = 0; const ok = s => console.log(`ok ${++n} - ${s}`)
try {
  fs.writeFileSync(path.join(dir, '.gitignore'), '.env\n.env.*\n!.env.example\nrelease/\nnode_modules\n*.key\n')
  fs.mkdirSync(path.join(dir, '.github', 'workflows'), { recursive: true })
  fs.writeFileSync(path.join(dir, 'README.md'), 'Documento pubblico')
  fs.writeFileSync(path.join(dir, '.env'), 'PRIVATE_CONFIGURATION')
  fs.writeFileSync(path.join(dir, '.env.example'), 'TOKEN=')
  fs.writeFileSync(path.join(dir, '.github/workflows/build.yml'), 'name: verifica')
  const good = scan(dir)
  assert.equal(good.failures.length, 0); assert.ok(good.excluded.includes('.env')); assert.ok(good.files.some(f => f.file === '.env.example'))
  ok('configurazione privata esclusa senza leggerla; esempio pubblico conservato')
  fs.writeFileSync(path.join(dir, 'README.md'), 'ghp_' + 'A'.repeat(36)); assert.ok(scan(dir).failures.some(f => f.endsWith('README.md')))
  fs.writeFileSync(path.join(dir, 'README.md'), 'Documento pubblico')
  fs.writeFileSync(path.join(dir, '.github/workflows/build.yml'), 'github_pat_' + 'A'.repeat(75))
  assert.ok(scan(dir).failures.some(f => f.endsWith('.github/workflows/build.yml')))
  ok('segreti nella radice e nei workflow intercettati, senza stamparne il valore')
  fs.writeFileSync(path.join(dir, '.github/workflows/build.yml'), 'name: verifica')
  fs.writeFileSync(path.join(dir, 'clienti.sqlite3'), 'Archivio sintetico');assert.ok(scan(dir).failures.some(f => f.includes('File riservato')))
  ok('database non escluso dalle regole impedisce il controllo positivo')
  assert.equal(ignored('documenti', true, ['/documenti/']), true); assert.equal(ignored('src/documenti', true, ['/documenti/']), false)
  assert.equal(ignored('.env.example', false, ['.env.*', '!.env.example']), false)
  assert.equal(ignored('src/.env.local', false, ['.env.*']), true)
  ok('regole correnti con ancoraggio, cartelle e negazione rispettate')
} finally { fs.rmSync(dir, { recursive: true, force: true }) }
console.log(`${n} prove pubblicazione superate`)
