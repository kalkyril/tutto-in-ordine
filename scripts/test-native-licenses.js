'use strict'
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), os = require('node:os')
const { verify, sha256 } = require('./check-native-licenses')
const project = path.resolve(__dirname, '..'), tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mngmnt-native-licenses-'))
const modules = path.join(project, 'node_modules'), fixture = path.join(tmp, 'project')
fs.mkdirSync(path.join(fixture, 'licenses'), { recursive: true })
fs.cpSync(path.join(project, 'licenses', 'native'), path.join(fixture, 'licenses', 'native'), { recursive: true })
fs.copyFileSync(path.join(project, 'package.json'), path.join(fixture, 'package.json'))
const file = path.join(fixture, 'licenses', 'native', 'manifest.json'), original = fs.readFileSync(file), catalog = JSON.parse(original)
const check = () => verify({ root: fixture, modules })
const installed = catalog.artifacts.find(a => a.package.startsWith('@napi-rs/canvas-') && fs.existsSync(path.join(modules, a.package, a.file)))
assert.ok(installed, 'Serve il modulo grafico della piattaforma di prova')
const target = installed.package.replace('@napi-rs/canvas-', '')
let n = 0; const ok = name => console.log(`ok ${++n} - ${name}`)
try {
  assert.equal(check().components, catalog.components.length)
  assert.ok(verify({ root: fixture, modules, target }).artifacts > 200)
  ok('binari installati e SBOM upstream corrispondono alla raccolta verificata')
  const notice = path.join(fixture, 'licenses', 'native', catalog.files[0].file), bytes = fs.readFileSync(notice)
  fs.unlinkSync(notice); assert.throws(check, /mancante\/modificato/); fs.writeFileSync(notice, bytes)
  fs.writeFileSync(notice, Buffer.alloc(bytes.length, 65)); assert.throws(check, /mancante\/modificato/); fs.writeFileSync(notice, bytes)
  ok('avviso assente o alterato a dimensione invariata impedisce la distribuzione')
  const mpl = catalog.components.find(c => c.license === 'MPL-2.0'), source = path.join(fixture, 'licenses', 'native', mpl.sourceArchive), sourceBytes = fs.readFileSync(source)
  fs.unlinkSync(source); assert.throws(check, /mancante\/modificato/); fs.writeFileSync(source, sourceBytes)
  const changed = structuredClone(catalog); delete changed.components.find(c => c.id === mpl.id).sourceArchive
  fs.writeFileSync(file, JSON.stringify(changed)); assert.throws(check, /Sorgente MPL/); fs.writeFileSync(file, original)
  ok('sorgenti MPL richiesti anche quando tutti i testi di licenza sono presenti')
  const tar = require('tar'), names = []
  tar.t({ file: source, sync: true, onReadEntry: entry => names.push(entry.path) })
  assert.ok(names.some(name => name.endsWith('/Cargo.toml'))); assert.ok(names.some(name => name.endsWith('.rs')))
  const font = catalog.components.find(c => c.id === 'liberation-fonts'), fontNames = []
  tar.t({ file: path.join(fixture, 'licenses', 'native', font.sourceArchive), sync: true, onReadEntry: entry => fontNames.push(entry.path) })
  for (const suffix of ['/src/LiberationSans-Regular.sfd', '/Makefile', '/COPYING', '/License.txt']) assert.ok(fontNames.some(name => name.endsWith(suffix)))
  ok('archivi forniti contengono sorgenti Rust/SFD, licenze e istruzioni di compilazione')
  const stale = structuredClone(catalog); stale.versions['@napi-rs/canvas'] = '0.0.0'
  fs.writeFileSync(file, JSON.stringify(stale)); assert.throws(check, /Versione da revisionare/); fs.writeFileSync(file, original)
  ok('aggiornare una dipendenza nativa richiede una nuova revisione delle licenze')
  assert.throws(() => verify({ root: fixture, modules, target: 'piattaforma-sconosciuta' }), /Architettura nativa/)
  ok('piattaforma senza evidenza e binario revisionato rifiutata')
  const artifact = installed
  const sbom = path.join(fixture, 'licenses', 'native', artifact.evidence), sbomBytes = fs.readFileSync(sbom), badSbom = JSON.parse(sbomBytes)
  badSbom.components.find(c => c.type === 'file').hashes[0].content = '0'.repeat(64); fs.writeFileSync(sbom, JSON.stringify(badSbom))
  const semantic = structuredClone(catalog); semantic.files.find(e => e.file === artifact.evidence).sha256 = sha256(sbom)
  fs.writeFileSync(file, JSON.stringify(semantic)); assert.throws(() => verify({ root: fixture, modules, target }), /SBOM non corrispondente/)
  fs.writeFileSync(file, original); fs.writeFileSync(sbom, sbomBytes)
  ok('SBOM con hash del binario differente rifiutato anche se il file è integro')
  const fakeModules = path.join(tmp, 'node_modules'); fs.mkdirSync(path.join(fakeModules, 'fixture-native'), { recursive: true })
  fs.writeFileSync(path.join(fakeModules, 'fixture-native', 'package.json'), JSON.stringify({ name: 'fixture-native', version: '1.0.0' }))
  fs.writeFileSync(path.join(fakeModules, 'fixture-native', 'nuovo.wasm'), 'wasm')
  const minimal = structuredClone(catalog); minimal.versions = {}
  fs.writeFileSync(file, JSON.stringify(minimal)); fs.writeFileSync(path.join(fixture, 'package.json'), JSON.stringify({ dependencies: { 'fixture-native': '1.0.0' } }))
  assert.throws(() => verify({ root: fixture, modules: fakeModules }), /Nuovo componente nativo/)
  ok('nuova libreria binaria non censita intercettata anche fuori dalle dipendenze precedenti')
  const pdf = path.join(fakeModules, 'pdfjs-dist'); fs.mkdirSync(path.join(pdf, 'wasm'), { recursive: true })
  fs.writeFileSync(path.join(pdf, 'package.json'), JSON.stringify({ name: 'pdfjs-dist', version: '6.4.299' })); fs.writeFileSync(path.join(pdf, 'wasm', 'quickjs-eval.wasm'), 'wasm')
  fs.writeFileSync(path.join(fixture, 'package.json'), JSON.stringify({ dependencies: { 'pdfjs-dist': '6.4.299' } }))
  assert.throws(() => verify({ root: fixture, modules: fakeModules, packaged: true }), /Componente escluso ancora presente/)
  ok('sandbox QuickJS inutilizzato non può rientrare accidentalmente negli installer')
  fs.writeFileSync(file, original)
  const escape = structuredClone(catalog); escape.files[0].file = '../../fuori.txt'; fs.writeFileSync(file, JSON.stringify(escape))
  assert.throws(check, /Percorso licenza/)
  ok('catalogo con percorsi fuori dalla raccolta rifiutato')
} finally { fs.rmSync(tmp, { recursive: true, force: true }) }
console.log(`${n} prove licenze native superate`)
